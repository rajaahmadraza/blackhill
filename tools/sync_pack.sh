#!/usr/bin/env bash
# Builds the ChatGPT review bundle from the repo (the single source of truth).
#
# Usage:
#   bash tools/sync_pack.sh              # diff since last review tag (or HEAD~1)
#   bash tools/sync_pack.sh <base-ref>   # diff since a specific commit/tag
#   bash tools/sync_pack.sh --mark       # after a review is done: move the review tag to HEAD
#
# Outputs (upload both to the ChatGPT review chat):
#   docs/handoff/SYNC_PACK.md      state + decisions + current slice spec + git facts
#   docs/handoff/REVIEW_DIFF.patch code changes since base (secrets/uploads excluded)
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
OUT_DIR="docs/handoff"
PACK="$OUT_DIR/SYNC_PACK.md"
DIFF="$OUT_DIR/REVIEW_DIFF.patch"
REVIEW_TAG="review/last"
MAX_DIFF_BYTES=400000
mkdir -p "$OUT_DIR"

if [[ "${1:-}" == "--mark" ]]; then
  git tag -f "$REVIEW_TAG" HEAD >/dev/null
  echo "Review tag moved to $(git rev-parse --short HEAD)"
  exit 0
fi

if [[ -n "${1:-}" ]]; then
  BASE="$1"
elif git rev-parse -q --verify "$REVIEW_TAG" >/dev/null; then
  BASE="$REVIEW_TAG"
else
  BASE="$(git rev-list --max-parents=0 HEAD | tail -1)"
fi

if [[ -n "$(git status --porcelain -- . ':!docs/handoff')" ]]; then
  DIRTY="YES — uncommitted changes exist; review covers committed code only"
else
  DIRTY="no"
fi

SLICE="$(grep -m1 -E '^- Current slice:' docs/STATE.md | sed -E 's/^- Current slice:[[:space:]]*//; s/[[:space:]].*$//' || true)"
SLICE_FILE=""
if [[ -n "$SLICE" ]]; then
  SLICE_FILE="$(ls docs/slices/${SLICE}*.md 2>/dev/null | head -1 || true)"
fi

EXCLUDES=(':!*.env' ':!.env*' ':!private_uploads' ':!media' ':!*.sqlite3' ':!*.dump' ':!*.sql'
          ':!*.pem' ':!*.key' ':!docs/handoff' ':!*.lock' ':!package-lock.json' ':!poetry.lock')

git diff "$BASE"..HEAD -- . "${EXCLUDES[@]}" > "$DIFF"
DIFF_SIZE=$(wc -c < "$DIFF")
TRUNC_NOTE=""
if (( DIFF_SIZE > MAX_DIFF_BYTES )); then
  head -c "$MAX_DIFF_BYTES" "$DIFF" > "$DIFF.tmp" && mv "$DIFF.tmp" "$DIFF"
  TRUNC_NOTE="TRUNCATED at ${MAX_DIFF_BYTES} bytes (full size ${DIFF_SIZE}). Review the file list; ask for specific files."
fi

{
  echo "# Blackhill SYNC PACK"
  echo
  echo "Generated by tools/sync_pack.sh — the only authoritative snapshot for this review."
  echo "If something is not in this pack or REVIEW_DIFF.patch, the reviewer must say 'not in provided context'."
  echo
  echo "## Git facts (from commands, not memory)"
  echo "- Generated: $(date -u +'%Y-%m-%d %H:%M UTC')"
  echo "- Branch: $(git rev-parse --abbrev-ref HEAD)"
  echo "- HEAD: $(git rev-parse --short HEAD) — $(git log -1 --pretty=%s)"
  echo "- Review base: $(git rev-parse --short "$BASE") ($BASE)"
  echo "- Uncommitted changes: $DIRTY"
  echo "- Diff size: ${DIFF_SIZE} bytes ${TRUNC_NOTE}"
  echo
  echo "### Commits in this review"
  echo '```'
  git log --oneline "$BASE"..HEAD | head -50
  echo '```'
  echo
  echo "### Files changed"
  echo '```'
  git diff --stat "$BASE"..HEAD -- . "${EXCLUDES[@]}" | tail -60
  echo '```'
  echo
  echo "---"
  echo "## docs/STATE.md"
  cat docs/STATE.md
  echo
  echo "---"
  echo "## docs/DECISIONS.md"
  cat docs/DECISIONS.md
  echo
  echo "---"
  if [[ -n "$SLICE_FILE" ]]; then
    echo "## Current slice spec: $SLICE_FILE"
    cat "$SLICE_FILE"
  else
    echo "## Current slice spec: NOT FOUND (STATE.md says '${SLICE:-none}')"
  fi
} > "$PACK"

echo "Wrote $PACK ($(wc -c < "$PACK") bytes) and $DIFF (${DIFF_SIZE} bytes) — base $(git rev-parse --short "$BASE")"
[[ -n "$TRUNC_NOTE" ]] && echo "WARNING: $TRUNC_NOTE"
exit 0
